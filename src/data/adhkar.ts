export const ALL_DHIKR: Dhikr[] = CATEGORIES.flatMap((c) => c.items);

export function findDhikr(id: string): Dhikr | undefined {
  return ALL_DHIKR.find((d) => d.id === id);
}

export function getCategory(id: string): Category | undefined {
  return CATEGORIES.find((c) => c.id === id);
}

// دعاء اليوم: يتغيّر كل يوم من الأدعية القرآنية
export function duaOfTheDay(date = new Date()): Dhikr {
  const quran = getCategory('quran')!.items;
  const start = new Date(date.getFullYear(), 0, 0).getTime();
  const day = Math.floor((date.getTime() - start) / 86400000);
  return quran[day % quran.length];
}
